#!/usr/bin/env bash
# 在 VPS 上为 /vip/ 配置 HTTP Basic Auth（写入 /etc/caddy/vip.conf 并 reload），支持多账号。
# 本机执行（用户名密码成对传入）：
#   ssh aliyun "bash -s -- vip <pass> bluewave <pass>" < deploy/vip-auth-setup.sh
# 密码位置留空（传 ""）则随机生成并打印一次；不传参数则默认生成 vip 账号。
#
# 说明：
# - 认证范围覆盖 /vip 全路径（含图片等子资源，follow_up 已迁入 /vip/follow_up/）。
#   同源 <img> 请求浏览器会自动附带 Basic 凭据，图片无需豁免；
#   豁免静态资源会导致内部架构图匿名可下载。
# - 旧路径 /follow_up/* 301 重定向到 /vip/follow_up/*。
set -euo pipefail

if [[ $(id -u) -ne 0 ]]; then
    echo "请用 root 运行" >&2
    exit 2
fi

args=("$@")
if (( ${#args[@]} == 0 )); then
    args=(vip "")
fi
if (( ${#args[@]} % 2 == 1 )); then
    args+=("")
fi

cred_lines=()
generated_report=""
for ((i = 0; i < ${#args[@]}; i += 2)); do
    u="${args[i]}"
    p="${args[i + 1]}"
    if [[ -z $p ]]; then
        p=$(openssl rand -base64 12 | tr '+/' 'Aa')
        generated_report+="  ${u} : ${p}"$'\n'
    fi
    h=$(caddy hash-password --plaintext "$p")
    cred_lines+=("	${u} ${h}")
done

{
    echo "# VIP auth (generated by deploy/vip-auth-setup.sh). Caddy 2.6: basicauth; 2.7+: basic_auth."
    echo "@vip path /vip /vip/*"
    echo "basicauth @vip {"
    printf '%s\n' "${cred_lines[@]}"
    echo "}"
    echo ""
    echo "# legacy /follow_up/* -> /vip/follow_up/*"
    echo "@oldfu path_regexp oldfu ^/follow_up(/.*)?$"
    echo "redir @oldfu /vip/follow_up{re.oldfu.1} 301"
} > /etc/caddy/vip.conf

caddy fmt --overwrite /etc/caddy/vip.conf >/dev/null 2>&1 || true
systemctl reload caddy 2>/dev/null || systemctl restart caddy

echo "---- VIP auth updated: ${args[0]} etc, $((${#args[@]} / 2)) account(s) ----"
if [[ -n $generated_report ]]; then
    echo "随机生成的密码（仅显示这一次，请立即保存）："
    printf '%s' "$generated_report"
fi
